const today = new Date();

/** ISO yyyy-MM-dd offset from today by `days`. */
function iso(days: number): string {
  const d = new Date(today);
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0, 10);
}

function isoTime(daysAgo: number, hours = 0): string {
  const d = new Date(today);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(d.getHours() - hours);
  return d.toISOString();
}

function daysDiff(isoDate: string): number {
  const target = new Date(isoDate + 'T00:00:00');
  const base = new Date(today.toISOString().slice(0, 10) + 'T00:00:00');
  return Math.round((target.getTime() - base.getTime()) / 86_400_000);
}

const FREQ_MONTHS: Record<PremiumFrequency, number> = {
  monthly: 1,
  quarterly: 3,
  half_yearly: 6,
  yearly: 12,
  annual: 12,
};

function buildSchedule(
  policyId: string,
  startISO: string,
  frequency: PremiumFrequency,
  amount: number,
  count: number,
): PremiumScheduleItem[] {
  const step = FREQ_MONTHS[frequency];
  const start = new Date(startISO + 'T00:00:00');
  const items: PremiumScheduleItem[] = [];
  for (let i = 0; i < count; i++) {
    const d = new Date(start);
    d.setMonth(d.getMonth() + step * i);
    const dueISO = d.toISOString().slice(0, 10);
    const delta = daysDiff(dueISO);
    const status = delta < -3 ? 'paid' : delta < 0 ? 'overdue' : 'upcoming';
    items.push({
      id: `${policyId}-prem-${i + 1}`,
      due_date: dueISO,
      amount,
      status,
      paid_date: status === 'paid' ? dueISO : null,
    });
  }
  return items;
}

function nextPremiumDate(schedule: PremiumScheduleItem[]): string {
  const next = schedule.find((s) => s.status !== 'paid');
  return next ? next.due_date : schedule[schedule.length - 1].due_date;
}

